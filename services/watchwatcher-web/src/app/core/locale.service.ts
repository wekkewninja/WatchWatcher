export type TranslationKey = keyof typeof englishCatalog;
export type Locale = 'en';

@Injectable({ providedIn: 'root' })
export class LocaleService {
  readonly locale = signal<Locale>(this.readLocale());

  translate(key: TranslationKey, parameters: Record<string, string | number> = {}): string {
    const message = englishCatalog[key];
    if (message === undefined) throw new Error(`Missing English translation: ${key}`);
    return message.replace(/\{([a-zA-Z0-9_]+)\}/g, (_match, name: string) => {
      const value = parameters[name];
      if (value === undefined) throw new Error(`Missing interpolation value "${name}" for ${key}`);
      return String(value);
    });
  }

  setLocale(locale: string): void {
    if (locale !== 'en') throw new Error(`Unsupported locale: ${locale}`);
    this.locale.set(locale);
    try { localStorage.setItem('app-locale', locale); } catch { }
  }

  private readLocale(): Locale {
    try {
      const savedLocale = localStorage.getItem('app-locale');
      return savedLocale === 'en' ? savedLocale : 'en';
    } catch { return 'en'; }
  }
}

@Pipe({ name: 't', standalone: true, pure: false })
export class TranslationPipe implements PipeTransform {
  constructor(private readonly locales: LocaleService) {}

  transform(key: TranslationKey, parameters: Record<string, string | number> = {}): string {
    this.locales.locale();
    return this.locales.translate(key, parameters);
  }
}